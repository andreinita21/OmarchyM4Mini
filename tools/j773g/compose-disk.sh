#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Lay the J773g Omarchy image (root.img, boot.img, esp/) into one GPT disk
# image and pull out the rung-u0 boot kit. Runs as root inside the Arch Linux
# ARM container (tools/j773g-disk.sh and tools/j773g-image-smoke.sh call it).
#
#   compose-disk.sh <image dir> <out dir>
#
# Writes to <out dir>:
#   disk.img       sparse GPT disk: EFI (500 MB, FAT, volume id 4F4D-5801,
#                  the esp/ tree), Boot (2 GiB, boot.img), Root (root.img),
#                  the layout the Gravity installer would produce
#   disk.env       ROOT_UUID, BOOT_UUID, partition offsets, image size
#   u0/vmlinuz, u0/Image.gz  the packaged kernel (arm64 Image) out of boot.img,
#                  plain for QEMU and gzip-suffixed for m1n1's linux.py
#   u0/initramfs.img  the image's initramfs (built by mkinitcpio inside the
#                  image: Omarchy's Mac hooks, uas/usb-storage/xhci/dwc3/btrfs)
#   u0/cmdline     the root= options rung u0 appends to the ladder's BOOT_ARGS
# The inputs are never modified.
set -euo pipefail
IMG=${1:?usage: compose-disk.sh <image dir> <out dir>}
OUT=${2:?usage: compose-disk.sh <image dir> <out dir>}
KERNEL=${KERNEL:-linux-gravity-m4}
# Sectors (512 B), as the smoke test and the plan's §5 layout use them.
ESP_START=2048; ESP_SECTORS=1024000          # 500 MB
BOOT_START=$((ESP_START + ESP_SECTORS)); BOOT_SECTORS=4194304   # 2 GiB
ROOT_START=$((BOOT_START + BOOT_SECTORS))
ESP_VOLID=4f4d5801                            # omarchy-mac-boot hardcodes 4F4D-5801

for f in "$IMG/root.img" "$IMG/boot.img" "$IMG/esp/m1n1/boot.bin" "$IMG/esp/EFI/BOOT/BOOTAA64.EFI"; do
  [[ -s $f ]] || { echo "compose-disk: missing $f (run tools/j773g-image.sh)" >&2; exit 1; }
done
mkdir -p "$OUT/u0"
root_bytes=$(stat -c %s "$IMG/root.img")
boot_bytes=$(stat -c %s "$IMG/boot.img")
(( boot_bytes <= BOOT_SECTORS * 512 )) || { echo "compose-disk: boot.img larger than the 2 GiB Boot partition" >&2; exit 1; }
root_sectors=$(( (root_bytes + 511) / 512 ))
# Alignment slack plus the backup GPT.
total_sectors=$(( ROOT_START + root_sectors + 2048 + 34 ))

echo "compose-disk: GPT disk $(( total_sectors / 2048 )) MiB (EFI 500 MB, Boot 2 GiB, Root $(( root_bytes / 1048576 )) MiB)"
rm -f "$OUT/disk.img" "$OUT/esp.img"
truncate -s $(( total_sectors * 512 )) "$OUT/disk.img"
printf 'label: gpt\nunit: sectors\nstart=%s, size=%s, type=C12A7328-F81F-11D2-BA4B-00A0C93EC93B, name=EFI\nstart=%s, size=%s, type=0FC63DAF-8483-4772-8E79-3D69D8477DE4, name=Boot\nstart=%s, size=%s, type=0FC63DAF-8483-4772-8E79-3D69D8477DE4, name=Root\n' \
  "$ESP_START" "$ESP_SECTORS" "$BOOT_START" "$BOOT_SECTORS" "$ROOT_START" "$root_sectors" | sfdisk -q "$OUT/disk.img"

truncate -s $(( ESP_SECTORS * 512 )) "$OUT/esp.img"
mkfs.vfat -F 32 -n OMARCHYESP -i "$ESP_VOLID" "$OUT/esp.img" >/dev/null
mcopy -i "$OUT/esp.img" -s -p "$IMG"/esp/* ::/
dd if="$OUT/esp.img" of="$OUT/disk.img" bs=512 seek=$ESP_START conv=notrunc,sparse status=none
rm -f "$OUT/esp.img"
dd if="$IMG/boot.img" of="$OUT/disk.img" bs=1M seek=$(( BOOT_START / 2048 )) conv=notrunc,sparse status=none
dd if="$IMG/root.img" of="$OUT/disk.img" bs=1M seek=$(( ROOT_START / 2048 )) conv=notrunc,sparse status=none

# Identities out of the images themselves (fstab is authoritative for root=).
mnt=$(mktemp -d)
mount -o loop,ro,subvol=@ "$IMG/root.img" "$mnt"
root_uuid=$(sed -n 's/^UUID=\([^ ]*\)[[:space:]]*\/[[:space:]].*/\1/p' "$mnt/etc/fstab" | head -1)
boot_uuid=$(sed -n 's/^UUID=\([^ ]*\)[[:space:]]*\/boot[[:space:]].*/\1/p' "$mnt/etc/fstab" | head -1)
umount "$mnt"; rmdir "$mnt"
[[ -n $root_uuid ]] || { echo "compose-disk: no root UUID in the image's fstab" >&2; exit 1; }

# Rung-u0 kit: kernel and initramfs the image booted in QEMU, out of boot.img.
# m1n1's linux.py picks the decompressor from the suffix, so the kernel is
# re-packed as Image.gz (the package ships the plain arm64 Image).
rm -f "$OUT/u0/vmlinuz" "$OUT/u0/Image.gz" "$OUT/u0/initramfs.img"
debugfs -R "dump /vmlinuz-$KERNEL $OUT/u0/vmlinuz" "$IMG/boot.img" 2>/dev/null
debugfs -R "dump /initramfs-$KERNEL.img $OUT/u0/initramfs.img" "$IMG/boot.img" 2>/dev/null
[[ -s $OUT/u0/vmlinuz && -s $OUT/u0/initramfs.img ]] || { echo "compose-disk: boot.img lacks vmlinuz-$KERNEL or its initramfs" >&2; exit 1; }
gzip -9 -n -k "$OUT/u0/vmlinuz" && mv "$OUT/u0/vmlinuz.gz" "$OUT/u0/Image.gz"
# What Limine passes (limine.conf), minus the quiet/splash options: a first
# boot on the mini wants the console. Omarchy's identities are fixed, so this
# is stable across image builds.
printf 'root=UUID=%s rw rootflags=subvol=@,x-systemd.device-timeout=0 rootfstype=btrfs zswap.enabled=0\n' "$root_uuid" >"$OUT/u0/cmdline"

cat >"$OUT/disk.env" <<EOF
# generated by tools/j773g/compose-disk.sh $(date -u +%Y-%m-%dT%H:%M:%SZ)
ROOT_UUID=$root_uuid
BOOT_UUID=$boot_uuid
ESP_VOLID=$ESP_VOLID
ESP_START=$ESP_START
BOOT_START=$BOOT_START
ROOT_START=$ROOT_START
ROOT_SECTORS=$root_sectors
DISK_SECTORS=$total_sectors
KERNEL=$KERNEL
KERNEL_RELEASE=$(strings -n 8 "$OUT/u0/vmlinuz" | grep -m1 -oE '[0-9]+\.[0-9]+\.[0-9]+-[0-9]+-[0-9]+-ARCH' || true)
EOF
chmod 644 "$OUT/disk.env" "$OUT/u0/"* "$OUT/disk.img"
echo "compose-disk: root UUID $root_uuid; kit in $OUT/u0 ($(du -h "$OUT/u0/vmlinuz" | cut -f1) kernel, $(du -h "$OUT/u0/initramfs.img" | cut -f1) initramfs)"
