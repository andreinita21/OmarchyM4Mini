#!/bin/bash
# SPDX-License-Identifier: MIT
# Runs INSIDE the omarchy-j773g-build container (see tools/j773g-build.sh).
#   /repo  this repository (read-only)
#   /src   persistent volume: linux/ (Asahi freeze + T8132 patches), m1n1/
#   /out   build/j773g/ in the repository (git-ignored)
set -euo pipefail

LINUX_URL=https://github.com/AsahiLinux/linux.git
LINUX_SHA=77cb8f24c2381a8abb7272d7bbdec548d6426a8a
M1N1_URL=https://github.com/AsahiLinux/m1n1.git
M1N1_REF=${M1N1_REF:-main}
JOBS=${JOBS:-$(nproc)}
L=/src/linux
APPLE=$L/arch/arm64/boot/dts/apple

# SoC patches that apply to the mini (PLAN.md section 3). 0011, 0014 and 0016
# are J713 board fixes and stay out.
DT_PATCHES=(0001 0002 0003 0004 0005 0006 0007 0008 0009 0010 0012 0013 0015)
KERNEL_PATCHES=(m4-boot-hacks-7.1.9.patch nvme-apple-t8132-split-nvmmu.patch)

# Boot ladder (PLAN.md section 5): name -> layer flags.
declare -A RUNGS=(
  [r0-boot]=""
  [r1-smc]="SMC"
  [r2-storage]="SMC STORAGE"
  [r3-usb]="SMC STORAGE USB"
  [r4-pcie]="SMC STORAGE USB PCIE"
  [r5-atc23]="SMC STORAGE USB PCIE USB_ATC23"
  [rx-all]="SMC STORAGE USB USB_ATC23 PCIE THUNDERBOLT DISPLAY"
)

log() { printf '\n=== %s\n' "$*"; }

cmd_src() {
  if [[ ! -d $L/.git ]]; then
    log "fetching linux $LINUX_SHA"
    git init -q "$L"
    git -C "$L" fetch -q --depth 1 "$LINUX_URL" "$LINUX_SHA"
  fi
  git -C "$L" -c advice.detachedHead=false checkout -q -f "$LINUX_SHA"
  git -C "$L" clean -qfdx
  git -C "$L" -c user.name=build -c user.email=build@localhost \
    switch -q -C j773g-build
  for p in "${DT_PATCHES[@]}"; do
    f=$(ls /repo/patches/"$p"-*.patch)
    log "apply $(basename "$f")"
    git -C "$L" apply --whitespace=nowarn "$f"
  done
  for p in "${KERNEL_PATCHES[@]}"; do
    log "apply $p"
    git -C "$L" apply --whitespace=nowarn "/repo/patches-kernel/$p"
  done
  git -C "$L" add -A
  git -C "$L" -c user.name=build -c user.email=build@localhost \
    commit -qm "T8132 SoC DT patches + M4 boot hacks + split NVMMU"
  git -C "$L" log --oneline -1
}

sync_dts() {
  cp /repo/dts/*.dts /repo/dts/*.dtsi "$APPLE/"
  for r in "${!RUNGS[@]}"; do
    {
      echo "// SPDX-License-Identifier: GPL-2.0+ OR MIT"
      echo "// Generated by tools/j773g/inner-build.sh: boot-ladder rung $r"
      for flag in ${RUNGS[$r]}; do echo "#define J773G_LAYER_$flag"; done
      echo '#include "t8132-j773g.dts"'
    } > "$APPLE/t8132-j773g-$r.dts"
    grep -q "t8132-j773g-$r.dtb" "$APPLE/Makefile" ||
      echo "dtb-\$(CONFIG_ARCH_APPLE) += t8132-j773g-$r.dtb" >> "$APPLE/Makefile"
  done
}

cmd_dtbs() {
  sync_dts
  [[ -f $L/.config ]] || make -C "$L" -s ARCH=arm64 LLVM=1 defconfig
  mkdir -p /out/dtb
  local check=${CHECK:-}
  for r in $(printf '%s\n' "${!RUNGS[@]}" | sort); do
    log "dtb $r (layers: ${RUNGS[$r]:-none}) check=${check:-n}"
    rm -f "$APPLE/t8132-j773g-$r.dtb"
    make -C "$L" -s ARCH=arm64 LLVM=1 ${check:+CHECK_DTBS=y} "apple/t8132-j773g-$r.dtb" \
      2>&1 | tee "/out/dtb/t8132-j773g-$r.log"
    cp "$APPLE/t8132-j773g-$r.dtb" /out/dtb/
  done
  (cd /out/dtb && sha256sum ./*.dtb | cut -c1-16,65-)
}

cmd_config() {
  make -C "$L" -s ARCH=arm64 LLVM=1 defconfig
  (cd "$L" && scripts/kconfig/merge_config.sh -m .config /repo/tools/j773g/kernel.fragment >/dev/null)
  make -C "$L" -s ARCH=arm64 LLVM=1 olddefconfig
  log "fragment options that did not stick"
  local bad=0
  while IFS= read -r line; do
    [[ $line =~ ^(CONFIG_[A-Z0-9_]+)=(.*)$ ]] || continue
    local k=${BASH_REMATCH[1]} v=${BASH_REMATCH[2]} got
    got=$(grep -E "^$k=|^# $k is not set" "$L/.config" || true)
    if [[ $v == n ]]; then
      [[ -z $got || $got == "# $k is not set" ]] || { echo "  $k wanted n, got $got"; bad=1; }
    else
      [[ $got == "$k=$v" ]] || { echo "  $k wanted $v, got ${got:-<absent>}"; bad=1; }
    fi
  done < /repo/tools/j773g/kernel.fragment
  [[ $bad == 0 ]] && echo "  none"
  mkdir -p /out && cp "$L/.config" /out/kernel.config
}

cmd_kernel() {
  [[ -f $L/.config ]] || cmd_config
  sync_dts
  log "building Image.gz with $JOBS jobs"
  make -C "$L" -s ARCH=arm64 LLVM=1 -j"$JOBS" Image.gz
  cp "$L/arch/arm64/boot/Image.gz" /out/Image.gz
  make -C "$L" -s ARCH=arm64 LLVM=1 kernelrelease > /out/kernelrelease
  (cd /out && sha256sum Image.gz | cut -c1-16)
}

cmd_initramfs() {
  local d
  d=$(mktemp -d)
  mkdir -p "$d"/{bin,dev,proc,sys,tmp,mnt,root}
  cp /bin/busybox "$d/bin/busybox"
  cp /repo/tools/j773g/init "$d/init"
  chmod 755 "$d/init"
  mknod -m 600 "$d/dev/console" c 5 1 2>/dev/null || true
  mknod -m 666 "$d/dev/null" c 1 3 2>/dev/null || true
  (cd "$d" && find . -print0 | sort -z | cpio --null -o -H newc --quiet | gzip -9n) > /out/initramfs.cpio.gz
  rm -rf "$d"
  (cd /out && sha256sum initramfs.cpio.gz | cut -c1-16)
}

cmd_m1n1() {
  if [[ ! -d /src/m1n1/.git ]]; then
    git clone -q --recursive "$M1N1_URL" /src/m1n1
  fi
  git -C /src/m1n1 fetch -q origin
  git -C /src/m1n1 -c advice.detachedHead=false checkout -q "origin/$M1N1_REF" 2>/dev/null ||
    git -C /src/m1n1 -c advice.detachedHead=false checkout -q "$M1N1_REF"
  git -C /src/m1n1 submodule update -q --init --recursive
  make -C /src/m1n1 -s clean
  make -C /src/m1n1 -s -j"$JOBS" USE_CLANG=1 RELEASE=1
  mkdir -p /out/m1n1
  cp /src/m1n1/build/m1n1.bin /src/m1n1/build/m1n1.macho /out/m1n1/ 2>/dev/null || cp /src/m1n1/build/m1n1.bin /out/m1n1/
  git -C /src/m1n1 describe --always --tags > /out/m1n1/VERSION
  rsync -a --delete --exclude __pycache__ /src/m1n1/proxyclient/ /out/m1n1/proxyclient/
  cat /out/m1n1/VERSION
  (cd /out/m1n1 && sha256sum m1n1.bin | cut -c1-16)
}

case ${1:-} in
  src) cmd_src ;;
  config) cmd_config ;;
  dtbs) cmd_dtbs ;;
  check) CHECK=y cmd_dtbs ;;
  kernel) cmd_kernel ;;
  initramfs) cmd_initramfs ;;
  m1n1) cmd_m1n1 ;;
  all) cmd_src; cmd_config; cmd_dtbs; cmd_kernel; cmd_initramfs; cmd_m1n1 ;;
  shell) exec bash ;;
  *) echo "usage: $0 src|config|dtbs|check|kernel|initramfs|m1n1|all|shell" >&2; exit 2 ;;
esac
