#!/bin/bash
# SPDX-License-Identifier: MIT
# Runs INSIDE the omarchy-j773g-build container (see tools/j773g-build.sh).
#   /repo  this repository (read-only)
#   /src   persistent volume: kernel trees and m1n1 checkouts
#   /out   build/j773g/ in the repository (git-ignored)
#
# BASE=gravity (default): GravityLinux/linux gravity-m4, pinned below. Its
#   t8132-j773g.dts has booted Fedora on an M4 mini. The ladder rungs g0..g8
#   are that board file plus dts/t8132-j773g-ladder.dtsi. M4_HACKS=1 adds
#   upstream's m4-boot-hacks patch (Gravity boots without it).
#   Output: /out/Image.gz, /out/dtb/, /out/kernel.config
# BASE=asahi (legacy, 2026-10-13 plan): Asahi 77cb8f24c2 + upstream T8132
#   patches + dts/asahi/ layers, rungs r0..r5. Output: /out/asahi/
set -euo pipefail

BASE=${BASE:-gravity}
JOBS=${JOBS:-$(nproc)}
case $BASE in
  gravity)
    LINUX_URL=https://github.com/GravityLinux/linux.git
    LINUX_SHA=${GRAVITY_SHA:-4fc326f6c25ccceb7515e2635c22e01fde5d3bac}
    L=/src/gravity-linux
    O=/out
    DT_PATCHES=()
    KERNEL_PATCHES=()
    [[ ${M4_HACKS:-0} == 1 ]] && KERNEL_PATCHES=(m4-boot-hacks-7.1.9.patch)
    DTS_DIR=/repo/dts
    # rung -> ladder groups (dts/t8132-j773g-ladder.dtsi). Audio is never on.
    declare -A RUNGS=(
      [g0-boot]=""
      [g1-smc]="SMC"
      [g2-storage]="SMC STORAGE"
      [g3-usb]="SMC STORAGE USB"
      [g4-pcie]="SMC STORAGE USB PCIE"
      [g5-cpufreq]="SMC STORAGE USB PCIE CPUFREQ"
      [g6-display]="SMC STORAGE USB PCIE CPUFREQ DISPLAY"
      [g7-poweroff]="SMC STORAGE USB PCIE CPUFREQ DISPLAY PMU"
      [g8-gpu]="SMC STORAGE USB PCIE CPUFREQ DISPLAY PMU GPU"
    )
    ;;
  asahi)
    LINUX_URL=https://github.com/AsahiLinux/linux.git
    LINUX_SHA=77cb8f24c2381a8abb7272d7bbdec548d6426a8a
    L=/src/linux
    O=/out/asahi
    # SoC patches that apply to the mini. 0011, 0014 and 0016 are J713 board
    # fixes and stay out.
    DT_PATCHES=(0001 0002 0003 0004 0005 0006 0007 0008 0009 0010 0012 0013 0015)
    KERNEL_PATCHES=(m4-boot-hacks-7.1.9.patch nvme-apple-t8132-split-nvmmu.patch)
    DTS_DIR=/repo/dts/asahi
    declare -A RUNGS=(
      [r0-boot]=""
      [r1-smc]="SMC"
      [r2-storage]="SMC STORAGE"
      [r3-usb]="SMC STORAGE USB"
      [r4-pcie]="SMC STORAGE USB PCIE"
      [r5-atc23]="SMC STORAGE USB PCIE USB_ATC23"
    )
    ;;
  *) echo "BASE must be gravity or asahi" >&2; exit 2 ;;
esac
APPLE=$L/arch/arm64/boot/dts/apple

# M1N1_FLAVOUR=asahi (AsahiLinux/m1n1) or gravity (GravityLinux/bootloader,
# the m1n1 fork their J773g installer ships, with T8132 kboot fixes).
M1N1_FLAVOUR=${M1N1_FLAVOUR:-asahi}
case $M1N1_FLAVOUR in
  asahi) M1N1_URL=https://github.com/AsahiLinux/m1n1.git ;;
  gravity) M1N1_URL=https://github.com/GravityLinux/bootloader.git ;;
  *) echo "M1N1_FLAVOUR must be asahi or gravity" >&2; exit 2 ;;
esac
M1N1_REF=${M1N1_REF:-main}

log() { printf '\n=== %s\n' "$*"; }

cmd_src() {
  if [[ ! -d $L/.git ]]; then
    log "fetching linux $LINUX_SHA"
    git init -q "$L"
    git -C "$L" fetch -q --depth 1 "$LINUX_URL" "$LINUX_SHA"
  fi
  git -C "$L" -c advice.detachedHead=false checkout -q -f "$LINUX_SHA"
  git -C "$L" clean -qfdx
  git -C "$L" -c user.name=build -c user.email=build@localhost \
    switch -q -C j773g-build
  for p in ${DT_PATCHES[@]+"${DT_PATCHES[@]}"}; do
    f=$(ls /repo/patches/"$p"-*.patch)
    log "apply $(basename "$f")"
    git -C "$L" apply --whitespace=nowarn "$f"
  done
  for p in ${KERNEL_PATCHES[@]+"${KERNEL_PATCHES[@]}"}; do
    log "apply $p"
    git -C "$L" apply --whitespace=nowarn "/repo/patches-kernel/$p"
  done
  git -C "$L" add -A
  git -C "$L" -c user.name=build -c user.email=build@localhost \
    commit -qm "j773g build patches: ${DT_PATCHES[*]-} ${KERNEL_PATCHES[*]-}" --allow-empty
  git -C "$L" log --oneline -1
}

sync_dts() {
  cp "$DTS_DIR"/*.dts* "$APPLE/"
  for r in "${!RUNGS[@]}"; do
    {
      echo "// SPDX-License-Identifier: GPL-2.0+ OR MIT"
      echo "// Generated by tools/j773g/inner-build.sh ($BASE): boot-ladder rung $r"
      if [[ $BASE == gravity ]]; then
        for flag in ${RUNGS[$r]}; do echo "#define J773G_LADDER_$flag"; done
        echo '#include "t8132-j773g.dts"'
        echo '#include "t8132-j773g-ladder.dtsi"'
      else
        for flag in ${RUNGS[$r]}; do echo "#define J773G_LAYER_$flag"; done
        echo '#include "t8132-j773g.dts"'
      fi
    } > "$APPLE/t8132-j773g-$r.dts"
    grep -q "t8132-j773g-$r.dtb" "$APPLE/Makefile" ||
      echo "dtb-\$(CONFIG_ARCH_APPLE) += t8132-j773g-$r.dtb" >> "$APPLE/Makefile"
  done
}

cmd_dtbs() {
  sync_dts
  [[ -f $L/.config ]] || make -C "$L" -s ARCH=arm64 LLVM=1 defconfig
  mkdir -p "$O/dtb"
  local check=${CHECK:-} names
  names=$(printf '%s\n' "${!RUNGS[@]}" | sort)
  # The unmodified board file is the known-good control ("stock").
  [[ $BASE == gravity ]] && names="$names stock"
  for r in $names; do
    local target=t8132-j773g-$r
    [[ $r == stock ]] && target=t8132-j773g
    log "dtb $r (groups: ${RUNGS[$r]:-none}) check=${check:-n}"
    rm -f "$APPLE/$target.dtb"
    make -C "$L" -s ARCH=arm64 LLVM=1 ${check:+CHECK_DTBS=y} "apple/$target.dtb" \
      2>&1 | tee "$O/dtb/t8132-j773g-$r.log"
    cp "$APPLE/$target.dtb" "$O/dtb/t8132-j773g-$r.dtb"
  done
  (cd "$O/dtb" && sha256sum ./*.dtb | cut -c1-16,65-)
}

# merge_and_check <tree> <fragment...>: defconfig + fragments, then report
# every fragment option that did not end up in .config as written.
merge_and_check() {
  local tree=$1; shift
  make -C "$tree" -s ARCH=arm64 LLVM=1 ${RUSTVARS[@]+"${RUSTVARS[@]}"} defconfig
  (cd "$tree" && scripts/kconfig/merge_config.sh -m .config "$@" >/dev/null)
  make -C "$tree" -s ARCH=arm64 LLVM=1 ${RUSTVARS[@]+"${RUSTVARS[@]}"} olddefconfig
  log "fragment options that did not stick"
  local bad=0 line k v got
  while IFS= read -r line; do
    [[ $line =~ ^(CONFIG_[A-Z0-9_]+)=(.*)$ ]] || continue
    k=${BASH_REMATCH[1]} v=${BASH_REMATCH[2]}
    got=$(grep -E "^$k=|^# $k is not set" "$tree/.config" || true)
    if [[ $v == n ]]; then
      [[ -z $got || $got == "# $k is not set" ]] || { echo "  $k wanted n, got $got"; bad=1; }
    else
      [[ $got == "$k=$v" ]] || { echo "  $k wanted $v, got ${got:-<absent>}"; bad=1; }
    fi
  done < <(cat "$@")
  [[ $bad == 0 ]] && echo "  none"
  return 0
}

cmd_config() {
  merge_and_check "$L" /repo/tools/j773g/kernel.fragment
  mkdir -p "$O" && cp "$L/.config" "$O/kernel.config"
}

cmd_kernel() {
  [[ -f $L/.config ]] || cmd_config
  sync_dts
  log "building Image.gz with $JOBS jobs"
  make -C "$L" -s ARCH=arm64 LLVM=1 -j"$JOBS" Image.gz
  cp "$L/arch/arm64/boot/Image.gz" "$O/Image.gz"
  make -C "$L" -s ARCH=arm64 LLVM=1 kernelrelease > "$O/kernelrelease"
  git -C "$L" rev-parse HEAD > "$O/REVISION"
  (cd "$O" && sha256sum Image.gz | cut -c1-16)
}

# GPU kernel: same tree in a separate worktree (the main tree is built in
# place), Rust on, DRM_ASAHI_M4 built in. Gravity base only.
RUSTVARS=()
cmd_kernel_gpu() {
  [[ $BASE == gravity ]] || { echo "kernel-gpu needs BASE=gravity" >&2; exit 2; }
  local W=/src/gravity-linux-gpu
  RUSTVARS=(RUSTC=/usr/bin/rustc BINDGEN=/usr/bin/bindgen HOSTRUSTC=/usr/bin/rustc)
  if [[ ! -d $W ]]; then
    git -C "$L" worktree add -q --detach "$W" HEAD
  fi
  git -C "$W" -c advice.detachedHead=false checkout -q -f "$(git -C "$L" rev-parse HEAD)"
  make -C "$W" -s ARCH=arm64 LLVM=1 "${RUSTVARS[@]}" rustavailable
  [[ -f $W/.config ]] || merge_and_check "$W" /repo/tools/j773g/kernel.fragment /repo/tools/j773g/kernel-gpu.fragment
  log "building GPU Image.gz with $JOBS jobs"
  make -C "$W" -s ARCH=arm64 LLVM=1 "${RUSTVARS[@]}" -j"$JOBS" Image.gz
  cp "$W/arch/arm64/boot/Image.gz" "$O/Image-gpu.gz"
  cp "$W/.config" "$O/kernel-gpu.config"
  (cd "$O" && sha256sum Image-gpu.gz | cut -c1-16)
}

cmd_initramfs() {
  local d
  d=$(mktemp -d)
  mkdir -p "$d"/{bin,dev,proc,sys,tmp,mnt,root}
  cp /bin/busybox "$d/bin/busybox"
  cp /repo/tools/j773g/init "$d/init"
  chmod 755 "$d/init"
  mknod -m 600 "$d/dev/console" c 5 1 2>/dev/null || true
  mknod -m 666 "$d/dev/null" c 1 3 2>/dev/null || true
  (cd "$d" && find . -print0 | sort -z | cpio --null -o -H newc --quiet | gzip -9n) > /out/initramfs.cpio.gz
  rm -rf "$d"
  (cd /out && sha256sum initramfs.cpio.gz | cut -c1-16)
}

cmd_m1n1() {
  local M=/src/m1n1-$M1N1_FLAVOUR O=/out/m1n1
  [[ $M1N1_FLAVOUR == asahi ]] || O=/out/m1n1-$M1N1_FLAVOUR
  if [[ ! -d $M/.git ]]; then
    git clone -q "$M1N1_URL" "$M"
  fi
  git -C "$M" fetch -q origin
  git -C "$M" -c advice.detachedHead=false checkout -q "origin/$M1N1_REF" 2>/dev/null ||
    git -C "$M" -c advice.detachedHead=false checkout -q "$M1N1_REF"
  git -C "$M" submodule update -q --init --recursive
  make -C "$M" -s clean
  make -C "$M" -s -j"$JOBS" RELEASE=1
  mkdir -p "$O"
  cp "$M/build/m1n1.bin" "$O/"
  cp "$M/build/m1n1.macho" "$O/" 2>/dev/null || true
  git -C "$M" describe --always --tags > "$O/VERSION"
  git -C "$M" rev-parse HEAD >> "$O/VERSION"
  rsync -a --delete --exclude __pycache__ "$M/proxyclient/" "$O/proxyclient/"
  cat "$O/VERSION"
  (cd "$O" && sha256sum m1n1.bin | cut -c1-16)
}

case ${1:-} in
  src) cmd_src ;;
  config) cmd_config ;;
  dtbs) cmd_dtbs ;;
  check) CHECK=y cmd_dtbs ;;
  kernel) cmd_kernel ;;
  kernel-gpu) cmd_kernel_gpu ;;
  initramfs) cmd_initramfs ;;
  m1n1) cmd_m1n1 ;;
  all) cmd_src; cmd_config; cmd_dtbs; cmd_kernel; cmd_initramfs; cmd_m1n1 ;;
  shell) exec bash ;;
  *) echo "usage: $0 src|config|dtbs|check|kernel|kernel-gpu|initramfs|m1n1|all|shell  (env BASE=gravity|asahi)" >&2; exit 2 ;;
esac
